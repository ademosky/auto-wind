-- 0002 — YouTube видео за секое возило
--
-- Додава можност за видео презентација на огласот. Полето е незадолжително:
-- ако е празно, секцијата за видео едноставно не се прикажува на сајтот.
--
-- Скриптата е безбедна за извршување врз база со постоечки податоци
-- (само додава колона, ништо не брише и не менува).

alter table public.vehicles
  add column if not exists video_url text;

comment on column public.vehicles.video_url is
  'YouTube линк до видео од возилото — се внесува од admin панелот.';

-- Освежување на кешот, за да го види новото поле веднаш
notify pgrst, 'reload schema';

